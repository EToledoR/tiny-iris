# ------------------------------------------------------------
# Helpers
# ------------------------------------------------------------

def clean_text(text):
    """Basic cleanup without rewriting the original article."""
    text = text.replace("\r\n", "\n")
    text = re.sub(r"\n{3,}", "\n\n", text)
    text = re.sub(r"[ \t]+", " ", text)
    return text.strip()


def find_topics(title, text):
    """
    Assign possible topics using the title and the first
    part of the article.

    This is deliberately a simple heuristic.
    """

    sample = f"{title}\n{text[:5000]}".lower()

    matches = []

    for topic, keywords in TOPICS.items():
        score = sum(
            sample.count(keyword.lower())
            for keyword in keywords
        )

        if score > 0:
            matches.append((score, topic))

    matches.sort(reverse=True)

    return [topic for _, topic in matches]


def safe_filename(article_id, title):
    """Create a filesystem-safe filename."""

    title = re.sub(
        r"[^\w\- ]+",
        "",
        title,
        flags=re.UNICODE,
    )

    title = re.sub(
        r"\s+",
        "_",
        title.strip(),
    )

    title = title[:80]

    return f"{article_id}_{title}.txt"


def clear_previous_output():
    """
    Remove only the files generated by this script.

    The Hugging Face cache is NOT touched.
    """

    if ARTICLES_DIR.exists():
        for path in ARTICLES_DIR.glob("*.txt"):
            path.unlink()

    if METADATA_FILE.exists():
        METADATA_FILE.unlink()


