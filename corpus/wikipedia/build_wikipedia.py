# Main
# ------------------------------------------------------------

def main():

    ARTICLES_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Clean the partial output from previous attempts.
    clear_previous_output()

    dataset = load_dataset(
        DATASET,
        CONFIG,
        split="train",
        streaming=True,
    )

    topic_chars = {
        topic: 0
        for topic in TOPICS
    }

    total_chars = 0
    articles_saved = 0

    with METADATA_FILE.open(
        "w",
        encoding="utf-8",
    ) as metadata:

        for article in dataset:

            if total_chars >= TARGET_CHARS:
                break

            article_id = article["id"]
            title = article["title"]
            text = clean_text(article["text"])

            # Ignore very small articles.
            if len(text) < MIN_ARTICLE_CHARS:
                continue

            # Ignore huge articles.
            if len(text) > MAX_ARTICLE_CHARS:
                continue

            topics = find_topics(
                title,
                text,
            )

            if not topics:
                continue

            # Choose the matching topic with the least
            # amount of data collected so far.
            available_topics = [
                topic
                for topic in topics
                if topic_chars[topic]
                < MAX_CHARS_PER_TOPIC
            ]

            if not available_topics:
                continue

            topic = min(
                available_topics,
                key=lambda t: topic_chars[t],
            )

            remaining_topic = (
                MAX_CHARS_PER_TOPIC
                - topic_chars[topic]
            )

            remaining_total = (
                TARGET_CHARS
                - total_chars
            )

            max_chars = min(
                remaining_topic,
                remaining_total,
            )

            if len(text) > max_chars:
                continue

            filename = safe_filename(
                article_id,
                title,
            )

            output_path = (
                ARTICLES_DIR / filename
            )

            output_path.write_text(
                text + "\n",
                encoding="utf-8",
            )

            metadata.write(
                json.dumps(
                    {
                        "id": article_id,
                        "title": title,
                        "topic": topic,
                        "chars": len(text),
                        "url": article["url"],
                        "source": DATASET,
                        "config": CONFIG,
                    },
                    ensure_ascii=False,
                )
                + "\n"
            )

            topic_chars[topic] += len(text)
            total_chars += len(text)
            articles_saved += 1

            if articles_saved % 25 == 0:
                print(
                    f"Articles: {articles_saved:4d} | "
                    f"chars: {total_chars:8,d} | "
                    f"topic: {topic}"
                )

    print()
    print("=" * 60)
    print("Wikipedia extraction complete")
    print("=" * 60)
    print(f"Articles: {articles_saved}")
    print(f"Characters: {total_chars:,}")
    print()

    for topic, chars in topic_chars.items():
        print(
            f"{topic:15s} {chars:8,d}"
        )

    print()
    print(
        f"Articles directory: {ARTICLES_DIR}"
    )
    print(
        f"Metadata:           {METADATA_FILE}"
    )


if __name__ == "__main__":
    main()
